  const en = {};
  const zh = {};
  for (const pair of PAIRS) {
    const src = pair[0];
    const chinese = pair[1];
    if (Object.prototype.hasOwnProperty.call(en, src)) throw new Error('Duplicate dashboard string: ' + src);
    if (typeof chinese !== 'string' || !chinese.trim()) throw new Error('Empty Chinese string: ' + src);
    en[src] = src;
    zh[src] = chinese;
  }
  const STRINGS = { en, zh };

  function langGet() {
    let stored = null;
    try { stored = localStorage.getItem(LANG_KEY); } catch (e) { stored = null; }
    if (stored === 'en' || stored === 'zh') return stored;
    let nav = '';
    try { nav = String((typeof navigator !== 'undefined' && navigator && navigator.language) || ''); } catch (e) { nav = ''; }
    if (nav.toLowerCase().startsWith('zh')) return 'zh';
    return 'en';
  }

  function t(key, vars) {
    const lang = langGet();
    const pack = STRINGS[lang] || STRINGS.en;
    let s = pack[key];
    if (typeof s !== 'string' || !s.trim()) s = STRINGS.en[key];
    if (typeof s !== 'string' || !s.trim()) s = key == null ? '' : String(key);
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, name) => (vars[name] == null ? m : String(vars[name])));
    return s;
  }

  function langSet(value) {
    if (value !== 'en' && value !== 'zh' || value === langGet()) return;
    try { localStorage.setItem(LANG_KEY, value); }
    catch (e) {
      if (typeof F.toast === 'function') F.toast(t('Could not save the language preference: {name}', { name: e && e.name }), { tone: 'error' });
      return;
    }
    try { location.reload(); } catch (e) { /* not a browser */ }
  }

  function applyDom() {
    if (typeof document === 'undefined' || !document.documentElement || !document.querySelectorAll) return;
    document.documentElement.lang = langGet() === 'zh' ? 'zh-CN' : 'en';
    for (const el of document.querySelectorAll('[data-i18n]')) {
      const key = el.getAttribute('data-i18n');
      if (key) el.textContent = t(key);
    }
    for (const el of document.querySelectorAll('[data-i18n-aria]')) {
      const key = el.getAttribute('data-i18n-aria');
      if (key) el.setAttribute('aria-label', t(key));
    }
    for (const el of document.querySelectorAll('[data-i18n-tip]')) {
      const key = el.getAttribute('data-i18n-tip');
      if (key) el.setAttribute('data-tip', t(key));
    }
    for (const el of document.querySelectorAll('[data-i18n-placeholder]')) {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) el.setAttribute('placeholder', t(key));
    }
  }

  F.I18N = STRINGS;
  F.t = t;
  F.lang = { get: langGet, set: langSet };
  applyDom();
